export type MessageKey = keyof typeof ZH;

let locale: Locale = 'zh-cn';

export function getLocale(): Locale {
  return locale;
}

export function setLocale(next: Locale): void {
  locale = next;
}

export function resolveLocale(pref: string | undefined, vscodeLang: string): Locale {
  if (pref === 'en' || pref === 'zh-cn') {
    return pref;
  }
  return vscodeLang.toLowerCase().startsWith('zh') ? 'zh-cn' : 'en';
}

export function t(key: MessageKey, params?: Record<string, string | number>): string {
  const table = locale === 'en' ? EN : ZH;
  let text = table[key] ?? ZH[key];
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function displayGitShort(text: string): string {
  if (locale !== 'en') {
    return text;
  }
  if (text === '干净') {
    return t('git.clean');
  }
  return text
    .replace(/(\d+) 个已改/g, '$1 changed')
    .replace(/(\d+) 个新文件/g, '$1 new files')
    .replace(/，/g, ', ');
}

